-- Do not expose INSERT/UPDATE policies for commissions or wallet_transactions to customers.
-- Implement order creation, inventory checks, referral attribution, commissions and withdrawals
-- in authenticated Supabase Edge Functions or database functions with carefully reviewed permissions.
-- Never grant a customer ability to set their own role, referral parent, wallet balance or commission status.
