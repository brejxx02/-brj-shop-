-- BRJ SHOP starter schema. Review before running on an existing production project.
-- Run in Supabase SQL Editor. Do not paste any service-role secret into frontend files.
create extension if not exists pgcrypto;

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  full_name text,
  referral_code text unique,
  referred_by uuid references public.profiles(id) on delete set null,
  role text not null default 'customer' check (role in ('customer','seller','admin')),
  created_at timestamptz not null default now()
);

create table if not exists public.categories (
  id bigint generated by default as identity primary key,
  name text not null unique,
  slug text not null unique,
  created_at timestamptz not null default now()
);

create table if not exists public.products (
  id bigint generated by default as identity primary key,
  name text not null,
  description text,
  price numeric(10,2) not null check (price >= 0),
  image_url text,
  category text,
  stock integer not null default 0 check (stock >= 0),
  is_active boolean not null default true,
  seller_id uuid references public.profiles(id) on delete set null,
  created_at timestamptz not null default now()
);

create table if not exists public.orders (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users(id) on delete restrict,
  status text not null default 'pending' check (status in ('pending','confirmed','processing','shipped','delivered','cancelled','refunded')),
  subtotal numeric(12,2) not null default 0 check (subtotal >= 0),
  shipping_amount numeric(12,2) not null default 0 check (shipping_amount >= 0),
  total numeric(12,2) not null default 0 check (total >= 0),
  payment_method text not null default 'cod' check (payment_method in ('cod','online')),
  payment_status text not null default 'unpaid' check (payment_status in ('unpaid','pending','paid','failed','refunded')),
  shipping_address jsonb,
  created_at timestamptz not null default now()
);

create table if not exists public.order_items (
  id bigint generated by default as identity primary key,
  order_id uuid not null references public.orders(id) on delete cascade,
  product_id bigint references public.products(id) on delete set null,
  product_name text not null,
  unit_price numeric(10,2) not null check (unit_price >= 0),
  quantity integer not null check (quantity > 0),
  line_total numeric(12,2) not null check (line_total >= 0)
);

create table if not exists public.seller_applications (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null unique references auth.users(id) on delete cascade,
  business_name text not null,
  status text not null default 'pending' check (status in ('pending','approved','rejected')),
  created_at timestamptz not null default now()
);

create table if not exists public.referrals (
  id uuid primary key default gen_random_uuid(),
  referrer_id uuid not null references public.profiles(id) on delete restrict,
  referred_user_id uuid not null unique references public.profiles(id) on delete cascade,
  created_at timestamptz not null default now(),
  check (referrer_id <> referred_user_id)
);

create table if not exists public.commissions (
  id uuid primary key default gen_random_uuid(),
  beneficiary_id uuid not null references public.profiles(id) on delete restrict,
  order_id uuid references public.orders(id) on delete restrict,
  source_user_id uuid references public.profiles(id) on delete set null,
  level integer not null check (level between 1 and 5),
  rate numeric(6,3) not null check (rate >= 0 and rate <= 100),
  eligible_amount numeric(12,2) not null check (eligible_amount >= 0),
  amount numeric(12,2) not null check (amount >= 0),
  status text not null default 'pending' check (status in ('pending','approved','reversed','paid')),
  created_at timestamptz not null default now()
);

create table if not exists public.wallet_transactions (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references public.profiles(id) on delete restrict,
  commission_id uuid references public.commissions(id) on delete restrict,
  type text not null check (type in ('commission','withdrawal','reversal','adjustment')),
  amount numeric(12,2) not null,
  note text,
  created_at timestamptz not null default now()
);

create table if not exists public.withdrawal_requests (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references public.profiles(id) on delete restrict,
  amount numeric(12,2) not null check (amount > 0),
  payout_details jsonb,
  status text not null default 'pending' check (status in ('pending','approved','rejected','paid')),
  reviewed_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  reviewed_at timestamptz
);

create table if not exists public.admin_users (
  user_id uuid primary key references auth.users(id) on delete cascade,
  created_at timestamptz not null default now()
);

create index if not exists products_active_created_idx on public.products(is_active, created_at desc);
create index if not exists orders_user_created_idx on public.orders(user_id, created_at desc);
create index if not exists commissions_beneficiary_status_idx on public.commissions(beneficiary_id, status);
create index if not exists wallet_transactions_user_created_idx on public.wallet_transactions(user_id, created_at desc);
create index if not exists withdrawal_requests_user_status_idx on public.withdrawal_requests(user_id, status);

-- Enable RLS everywhere.
alter table public.profiles enable row level security;
alter table public.categories enable row level security;
alter table public.products enable row level security;
alter table public.orders enable row level security;
alter table public.order_items enable row level security;
alter table public.seller_applications enable row level security;
alter table public.referrals enable row level security;
alter table public.commissions enable row level security;
alter table public.wallet_transactions enable row level security;
alter table public.withdrawal_requests enable row level security;
alter table public.admin_users enable row level security;

-- Public catalog reads only active products. Admin mutations use admin_users.
drop policy if exists "Public can read active products" on public.products;
create policy "Public can read active products" on public.products for select using (is_active = true);
drop policy if exists "Admins can read all products" on public.products;
create policy "Admins can read all products" on public.products for select to authenticated
using (exists(select 1 from public.admin_users a where a.user_id = auth.uid()));
drop policy if exists "Admins can insert products" on public.products;
create policy "Admins can insert products" on public.products for insert to authenticated
with check (exists(select 1 from public.admin_users a where a.user_id = auth.uid()));
drop policy if exists "Admins can update products" on public.products;
create policy "Admins can update products" on public.products for update to authenticated
using (exists(select 1 from public.admin_users a where a.user_id = auth.uid()))
with check (exists(select 1 from public.admin_users a where a.user_id = auth.uid()));
drop policy if exists "Admins can delete products" on public.products;
create policy "Admins can delete products" on public.products for delete to authenticated
using (exists(select 1 from public.admin_users a where a.user_id = auth.uid()));

drop policy if exists "Users read own profile" on public.profiles;
create policy "Users read own profile" on public.profiles for select to authenticated using (id = auth.uid());
drop policy if exists "Users update own profile" on public.profiles;
create policy "Users update own profile" on public.profiles for update to authenticated using (id = auth.uid()) with check (id = auth.uid());
drop policy if exists "Admins read profiles" on public.profiles;
create policy "Admins read profiles" on public.profiles for select to authenticated using (exists(select 1 from public.admin_users a where a.user_id = auth.uid()));

drop policy if exists "Anyone can read categories" on public.categories;
create policy "Anyone can read categories" on public.categories for select using (true);
drop policy if exists "Admins manage categories" on public.categories;
create policy "Admins manage categories" on public.categories for all to authenticated
using (exists(select 1 from public.admin_users a where a.user_id = auth.uid()))
with check (exists(select 1 from public.admin_users a where a.user_id = auth.uid()));

drop policy if exists "Users read own orders" on public.orders;
create policy "Users read own orders" on public.orders for select to authenticated using (user_id = auth.uid());
drop policy if exists "Admins manage orders" on public.orders;
create policy "Admins manage orders" on public.orders for all to authenticated
using (exists(select 1 from public.admin_users a where a.user_id = auth.uid()))
with check (exists(select 1 from public.admin_users a where a.user_id = auth.uid()));

drop policy if exists "Users read own order items" on public.order_items;
create policy "Users read own order items" on public.order_items for select to authenticated
using (exists(select 1 from public.orders o where o.id = order_id and o.user_id = auth.uid()) or exists(select 1 from public.admin_users a where a.user_id = auth.uid()));
drop policy if exists "Admins manage order items" on public.order_items;
create policy "Admins manage order items" on public.order_items for all to authenticated
using (exists(select 1 from public.admin_users a where a.user_id = auth.uid()))
with check (exists(select 1 from public.admin_users a where a.user_id = auth.uid()));

drop policy if exists "Users read own seller application" on public.seller_applications;
create policy "Users read own seller application" on public.seller_applications for select to authenticated using (user_id = auth.uid());
drop policy if exists "Users submit seller application" on public.seller_applications;
create policy "Users submit seller application" on public.seller_applications for insert to authenticated with check (user_id = auth.uid());
drop policy if exists "Admins manage seller applications" on public.seller_applications;
create policy "Admins manage seller applications" on public.seller_applications for all to authenticated
using (exists(select 1 from public.admin_users a where a.user_id = auth.uid()))
with check (exists(select 1 from public.admin_users a where a.user_id = auth.uid()));

drop policy if exists "Users read own referrals" on public.referrals;
create policy "Users read own referrals" on public.referrals for select to authenticated using (referrer_id = auth.uid() or referred_user_id = auth.uid());
drop policy if exists "Admins read referrals" on public.referrals;
create policy "Admins read referrals" on public.referrals for select to authenticated using (exists(select 1 from public.admin_users a where a.user_id = auth.uid()));

drop policy if exists "Users read own commissions" on public.commissions;
create policy "Users read own commissions" on public.commissions for select to authenticated using (beneficiary_id = auth.uid());
drop policy if exists "Admins manage commissions" on public.commissions;
create policy "Admins manage commissions" on public.commissions for all to authenticated
using (exists(select 1 from public.admin_users a where a.user_id = auth.uid()))
with check (exists(select 1 from public.admin_users a where a.user_id = auth.uid()));

drop policy if exists "Users read own wallet transactions" on public.wallet_transactions;
create policy "Users read own wallet transactions" on public.wallet_transactions for select to authenticated using (user_id = auth.uid());
drop policy if exists "Admins manage wallet transactions" on public.wallet_transactions;
create policy "Admins manage wallet transactions" on public.wallet_transactions for all to authenticated
using (exists(select 1 from public.admin_users a where a.user_id = auth.uid()))
